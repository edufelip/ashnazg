#!/usr/bin/env python3
"""Provision an owned Binderfs fixture on disposable Linux CI, never a user's host."""
from __future__ import annotations

import argparse
import fcntl
import json
import os
from pathlib import Path
import platform
import stat
import struct
import subprocess
import uuid

NAMES = ('binder', 'hwbinder', 'vndbinder')
# Linux UAPI binderfs.h: _IOWR('b', 1, struct binderfs_device).
# char name[256], __u32 major, __u32 minor; Linux generic ioctl encoding.
BINDER_CTL_ADD = (3 << 30) | (264 << 16) | (ord('b') << 8) | 1


def is_character(path: Path) -> bool:
    try:
        return stat.S_ISCHR(path.stat().st_mode)
    except OSError:
        return False


def ensure_nodes(mountpoint: Path) -> None:
    """Create missing named devices through Binderfs, never ordinary mknod guesses."""
    for name in NAMES:
        path = mountpoint / name
        if is_character(path):
            continue
        if path.exists() or path.is_symlink():
            raise RuntimeError(f'refusing non-character Binderfs entry: {path}')
        with (mountpoint / 'binder-control').open('r+b', buffering=0) as control:
            device = bytearray(struct.pack('256sII', name.encode(), 0, 0))
            fcntl.ioctl(control.fileno(), BINDER_CTL_ADD, device, True)
        if not is_character(path):
            raise RuntimeError(f'Binderfs did not create a character device: {path}')
        path.chmod(0o666)


def link_nodes(mountpoint: Path, dev: Path = Path('/dev')) -> list[str]:
    created = []
    try:
        for name in NAMES:
            alias = dev / name
            if is_character(alias):
                continue
            if alias.exists() or alias.is_symlink():
                raise RuntimeError(f'refusing to replace foreign Binder entry: {alias}')
            alias.symlink_to(mountpoint / name)
            created.append(str(alias))
        return created
    except BaseException:
        for value in created:
            path = Path(value)
            if path.is_symlink() and os.readlink(path) == str(mountpoint / path.name):
                path.unlink()
        raise


def cleanup(state: dict) -> None:
    if not state.get('mountpoint'):
        return
    mountpoint = Path(state['mountpoint'])
    run_id = str(uuid.UUID(state['run_id']))
    if str(mountpoint) != '/dev/ashnazg-binder-' + run_id or mountpoint.is_symlink():
        raise RuntimeError('refusing invalid Binder fixture ownership record')
    for value in state.get('aliases', []):
        alias = Path(value)
        if alias.parent != Path('/dev') or alias.name not in NAMES:
            raise RuntimeError('refusing foreign alias in Binder fixture record')
        if alias.is_symlink() and os.readlink(alias) == str(mountpoint / alias.name):
            alias.unlink()
    if os.path.ismount(mountpoint):
        subprocess.run(['umount', str(mountpoint)], check=True, timeout=10)
    if mountpoint.exists():
        mountpoint.rmdir()


def provision(output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    state_file = output / 'binder-state.json'
    if state_file.exists() or state_file.is_symlink():
        raise RuntimeError('refusing to overwrite an existing Binder fixture receipt')
    run_id = str(uuid.uuid4())
    state = {'schema_version': 1, 'run_id': run_id, 'kernel': platform.release(),
             'mountpoint': None, 'aliases': []}
    if not all(is_character(Path('/dev') / n) for n in NAMES):
        for name in NAMES:
            path = Path('/dev') / name
            if (path.exists() or path.is_symlink()) and not is_character(path):
                raise RuntimeError(f'foreign non-character Binder entry: {path}')
        if 'binder' not in Path('/proc/filesystems').read_text().split():
            subprocess.run(['modprobe', 'binder_linux'], check=True, timeout=10)
        mountpoint = Path('/dev/ashnazg-binder-' + run_id)
        mountpoint.mkdir(mode=0o755)
        state['mountpoint'] = str(mountpoint)
        try:
            subprocess.run(['mount', '-t', 'binder', 'binder', str(mountpoint)], check=True, timeout=10)
            ensure_nodes(mountpoint)
            # Devices generated by the mount itself also need runner-user access.
            for name in NAMES:
                (mountpoint / name).chmod(0o666)
            state['aliases'] = link_nodes(mountpoint)
        except BaseException:
            cleanup(state)
            raise
    try:
        state_file.write_text(json.dumps(state, indent=2) + '\n')
    except BaseException:
        cleanup(state)
        raise
    print(json.dumps(state))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--cleanup', action='store_true')
    args = parser.parse_args()
    if platform.system() != 'Linux' or os.environ.get('GITHUB_ACTIONS') != 'true' or os.geteuid() != 0:
        parser.error('fixture provisioning is restricted to root on disposable Linux GitHub CI')
    if args.cleanup:
        state_file = args.output_dir / 'binder-state.json'
        if state_file.exists():
            cleanup(json.loads(state_file.read_text()))
    else:
        provision(args.output_dir)


if __name__ == '__main__':
    main()
